//Seleccionar todo de la tabla asunto
SELECT * FROM ASUNTO;

// Muestra a los clientes con sus asuntos
SELECT 
    C.NOMBRE CLIENTE,
    A.NUMERO_EXPEDIENTE,
    A.ESTADO,
    A.FECHA_INICIO,
    A.FECHA_FIN
FROM CLIENTE C,
     ASUNTO A
WHERE 1=1 
AND C.CLIENTE_ID = A.CLIENTE_ID
ORDER BY C.NOMBRE;
// Muestra los procuradores con sus asuntos
SELECT
    P.NOMBRE PROCURADOR,
    A.NUMERO_EXPEDIENTE EXPEDIENTE,
    A.ESTADO,
    C.NOMBRE CLIENTE
FROM 
    PROCURADOR P,
    ASUNTO A,
    CLIENTE C,
    ASUNTO_PROCURADOR AP
WHERE 1=1
AND P.PROCURADOR_ID = AP.PROCURADOR_ID
AND AP.ASUNTO_ID = A.ASUNTO_ID
AND C.CLIENTE_ID = A.CLIENTE_ID
ORDER BY P.NOMBRE, A.NUMERO_EXPEDIENTE;
// Muestra los asuntos en tramite
SELECT 
     A.NUMERO_EXPEDIENTE EXPEDIENTE,
     C.NOMBRE CLIENTE,
     A.FECHA_INICIO,
     A.ESTADO
FROM ASUNTO A,
     CLIENTE C
WHERE 1=1
AND C.CLIENTE_ID = A.CLIENTE_ID
AND A.ESTADO = 'En trámite'
ORDER BY FECHA_INICIO;
//Muestra cuantos asuntos lleva cada procurador
SELECT P.NOMBRE PROCURADOR,
       COUNT(AP.ASUNTO_ID) TOTAL_ASUNTOS
       
FROM PROCURADOR P,
     ASUNTO_PROCURADOR AP
WHERE 1=1 
AND P.PROCURADOR_ID = AP.PROCURADOR_ID
GROUP BY P.NOMBRE
ORDER BY TOTAL_ASUNTOS DESC;
// Muestra los dias transcurridos de cada asunto
SELECT 
    ASUNTO_ID,
    NUMERO_EXPEDIENTE,
    ESTADO,
    FECHA_INICIO,
    FECHA_FIN,
    CASE 
        WHEN FECHA_FIN IS NOT NULL THEN 
            ROUND(FECHA_FIN - FECHA_INICIO,2)       -- días entre inicio y fin
        ELSE 
            ROUND(SYSDATE - FECHA_INICIO,2)         -- días que lleva abierto
    END AS DIAS_TRANSCURRIDOS
FROM ASUNTO
ORDER BY FECHA_INICIO;
//Promedio de duración de los asuntos archivados
SELECT 
    ROUND(AVG(FECHA_FIN - FECHA_INICIO), 2) PROMEDIO_DIAS
FROM ASUNTO
WHERE FECHA_FIN IS NOT NULL;
//promedio de duración de asuntos en días
SELECT 
    ROUND(AVG(FECHA_FIN - FECHA_INICIO), 2) AS PROMEDIO_DIAS
FROM ASUNTO
WHERE FECHA_FIN IS NOT NULL;
// asunto más antiguo y asunto más reciente
SELECT 
    MIN(FECHA_INICIO) AS ASUNTO_MAS_ANTIGUO,
    MAX(FECHA_INICIO) AS ASUNTO_MAS_RECIENTE
FROM ASUNTO;
// Total de clientes registrados
SELECT COUNT(*) AS TOTAL_CLIENTES
FROM CLIENTE;
//promedio de duración del asunto, por estado
SELECT 
    ESTADO,
    ROUND(AVG(FECHA_FIN - FECHA_INICIO), 2) AS PROMEDIO_DIAS
FROM ASUNTO
WHERE FECHA_FIN IS NOT NULL
GROUP BY ESTADO;
//Cantidad de asuntos por cliente
SELECT 
    CLIENTE_ID,
    COUNT(*) AS TOTAL_ASUNTOS
FROM ASUNTO
GROUP BY CLIENTE_ID;
// Cantidad de procuradores asignados por asunto
SELECT 
    ASUNTO_ID,
    COUNT(PROCURADOR_ID) AS TOTAL_PROCURADORES
FROM ASUNTO_PROCURADOR
GROUP BY ASUNTO_ID;