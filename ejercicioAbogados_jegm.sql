CREATE TABLE CLIENTE (
    CLIENTE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DNI VARCHAR2(20),
    NOMBRE VARCHAR2(100) NOT NULL,
    DIRECCION VARCHAR2(200),
    TELEFONO VARCHAR2(20),
    EMAIL VARCHAR2(100)
);
CREATE TABLE PROCURADOR (
    PROCURADOR_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DNI VARCHAR2(20),
    NOMBRE VARCHAR2(100) NOT NULL,
    DIRECCION VARCHAR2(200),
    TELEFONO VARCHAR2(20),
    EMAIL VARCHAR2(100)
);
CREATE TABLE ASUNTO (
    ASUNTO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NUMERO_EXPEDIENTE NUMBER,
    CLIENTE_ID NUMBER NOT NULL,
    FECHA_INICIO DATE NOT NULL,
    FECHA_FIN DATE,
    ESTADO VARCHAR2(50)
);
CREATE TABLE ASUNTO_PROCURADOR (
    ASUNTO_ID NUMBER NOT NULL,
    PROCURADOR_ID NUMBER NOT NULL
);

ALTER TABLE ASUNTO ADD CONSTRAINT FK_ASUNTO_CLIENTE_ID
