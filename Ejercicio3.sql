

--CREAMOS LAS TABLAS
CREATE TABLE SOCIO(
ID_SOCIO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE NVARCHAR2(100) NOT NULL,
DIRECCION NVARCHAR2(100),
TELEFONO NUMBER(15)
);

CREATE TABLE BARCO(
MATRICULA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE NVARCHAR2(100) NOT NULL,
NUM_AMARRE NUMBER(10),
CUOTA NUMBER (10,2), --hasta 10 digitos y con 2 decimales
ID_SOCIO NUMBER
);

DROP TABLE BARCO CASCADE CONSTRAINTS;

CREATE TABLE PATRON(
ID_PATRON NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE NVARCHAR2(100) NOT NULL,
TELEFONO NUMBER(15),
DIRECCION NVARCHAR2(100)
);

CREATE TABLE SALIDA(
ID_SALIDA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
FECHA_SALIDA DATE NOT NULL,
HORA NVARCHAR2(10),
DESTINO NVARCHAR2 (100),
ID_PATRON NUMBER,
MATRICULA NUMBER
);

DROP TABLE SALIDA CASCADE CONSTRAINTS;

CREATE TABLE VIAJE(
ID_SALIDA NUMBER,
ID_SOCIO NUMBER,
PRIMARY KEY (ID_SALIDA , ID_SOCIO)
);




--CREAR LLAVES FORANEAS
