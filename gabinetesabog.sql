--  TABLAS 

CREATE TABLE CLIENTE (
  CLIENTE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  DNI        NVARCHAR2(20),
  NOMBRE     NVARCHAR2(120),
  DIRECCION  NVARCHAR2(200),
  TELEFONO   NVARCHAR2(20),
  CORREO     NVARCHAR2(120)
);

CREATE TABLE PROCURADOR (
  PROCURADOR_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  DNI           NVARCHAR2(20),
  NOMBRE        NVARCHAR2(120),
  DIRECCION     NVARCHAR2(200),
  TELEFONO      NVARCHAR2(20),
  CORREO        NVARCHAR2(120)
);

CREATE TABLE ESTADO (
  ESTADO_ID   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  DESCRIPCION NVARCHAR2(40)
);

CREATE TABLE PERIODO (
  PERIODO_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  FECHA_INICIO    DATE,
  FECHA_ARCHIVADO DATE,
  FECHA_FINAL     DATE
);

CREATE TABLE ASUNTO (
  ASUNTO_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NUM_EXPEDIENTE NVARCHAR2(40),
  CLIENTE_ID     NUMBER,
  ESTADO_ID      NUMBER,
  PERIODO_ID     NUMBER,
  DESCRIPCION    NVARCHAR2(4000)
);

CREATE TABLE ASUNTO_PROCURADOR (
  ASUNTO_ID     NUMBER,
  PROCURADOR_ID NUMBER,
  ROL           NVARCHAR2(40),
  FECHA_ASIGN   DATE
);


