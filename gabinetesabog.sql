-- 9. Procuradores con más de 1 año desde su FECHA_ASIGN al caso
-- para qué sirve: calcular antigüedad con MONTHS_BETWEEN
-- OJO: en nuestros inserts usamos SYSDATE así que probablemente da 0 filas,
-- pero la sintaxis es correcta

