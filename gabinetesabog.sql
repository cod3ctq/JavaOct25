-- 21. Duración promedio (en días) de los asuntos FINALIZADOS
-- para qué sirve: usar AVG() y restar fechas (FECHA_FINAL - FECHA_INICIO da días)
-------------------------------------------------
SELECT ROUND(AVG(P.FECHA_FINAL - P.FECHA_INICIO), 2) AS PROMEDIO_DIAS_DURACION
FROM ASUNTO A
JOIN PERIODO P ON A.PERIODO_ID = P.PERIODO_ID
JOIN ESTADO  E ON A.ESTADO_ID  = E.ESTADO_ID
WHERE P.FECHA_FINAL IS NOT NULL
  AND E.DESCRIPCION = 'FINALIZADO';
