CREATE TABLE PERSONA(
    PERSONA_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOMBRE NVARCHAR2(100),
    TELEFONO NVARCHAR2(10),
    EMAIL NVARCHAR2(50)
);

CREATE TABLE SOCIO(
    SOCIO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FECHA_DE_ALTA DATE,
    FECHA_DE_RENOVACION DATE,
    SOCIO_ACTIVO NVARCHAR2(2),
    NOMBRE NVARCHAR2(100),
    BARCO_ID NUMBER,
    --FK_NOMBRE DE LA TABLA QUE RECIBE_NOMBRE_DE_LA_COLUMNA_QUE_LO_RECIBE
    --FOREIGN KEY NOMBRE DE LA COLUMNA QUE RECIBE LA LLAVE
    --REFERENCES NOMBRE DE LA COLUMNA DE DONDE VIENE EL DATO
    CONSTRAINT FK_SOCIO_BARCO_ID FOREIGN KEY(BARCO_ID) REFERENCES PERSONA(PERSONA_ID)
);

CREATE TABLE BARCO(
    BARCO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NUMERO_MATRICULA NVARCHAR2(12),
    NOMBRE NVARCHAR2(30),
    NUMERO_AMARRE NVARCHAR2(3),
    CUOTA_PAGO NUMBER(6,2),
    PATRON_ID NUMBER,
    --FK_NOMBRE DE LA TABLA QUE RECIBE_NOMBRE_DE_LA_COLUMNA_QUE_LO_RECIBE
    --FOREIGN KEY NOMBRE DE LA COLUMNA QUE RECIBE LA LLAVE
    --REFERENCES NOMBRE DE LA COLUMNA DE DONDE VIENE EL DATO
    CONSTRAINT FK_BARCO_PATRON_ID FOREIGN KEY(PATRON_ID) REFERENCES PATRON(PATRON_ID)
);

CREATE TABLE SALIDA(
    SALIDA_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FECHA DATE,
    HORA TIMESTAMP,
    DESTINO_ID NUMBER,
    BARCO_ID NUMBER,
    --FK_NOMBRE DE LA TABLA QUE RECIBE_NOMBRE_DE_LA_COLUMNA_QUE_LO_RECIBE
    --FOREIGN KEY NOMBRE DE LA COLUMNA QUE RECIBE LA LLAVE
    --REFERENCES NOMBRE DE LA COLUMNA DE DONDE VIENE EL DATO
    CONSTRAINT FK_SALIDAS_DESTINO_ID FOREIGN KEY(DESTINO_ID) REFERENCES DESTINO(DESTINO_ID),
    CONSTRAINT FK_SALIDAS_BARCO_ID FOREIGN KEY(BARCO_ID) REFERENCES BARCO(BARCO_ID)
);

CREATE TABLE PATRON(
    PATRON_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PERSONA_ID NUMBER,
    CONSTRAINT FK_PATRON_PERSONA_ID FOREIGN KEY(PERSONA_ID) REFERENCES PERSONA(PERSONA_ID)
);

CREATE TABLE DESTINO(
    DESTINO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOMBRE NVARCHAR2(50)
);

