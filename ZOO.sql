
-- TABLAS

CREATE TABLE ZOOS(
ZOO_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE NVARCHAR2(100),
CIUDAD2_ID NUMBER,
PAIS_ID NUMBER,
TAMAÑO_M2 NVARCHAR2(20),
PRE_ANUAL NUMBER
);

CREATE TABLE ESPECIES (
ESPECIE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE_VULGAR VARCHAR2(100),
NOMBRE_CIENTIFICO VARCHAR2(150),
FAMILIA VARCHAR2(100),
PELIGRO_EXT CHAR(1) CHECK (PELIGRO_EXT IN ('S','N'))
);

CREATE TABLE ANIMALES (
ANIMAL_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
ESPECIE_ID NUMBER,
ZOO_ID NUMBER,
SEXO CHAR(1) CHECK (SEXO IN ('M','H')),
FECHA_NAC DATE,
PAIS_ORIGEN NUMBER, -- ES PAIS_ID
CONTINENTE_ID NUMBER,
NOMBRE_ANI NVARCHAR2(50)
);

CREATE TABLE PAISES (
PAIS_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE NVARCHAR2(50)
);

CREATE TABLE CIUDADES2 (
CIUDAD2_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE NVARCHAR2(50)
);

CREATE TABLE CONTINENTES (
CONTINENTE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOMBRE NVARCHAR2(50)
);

