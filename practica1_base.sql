
--CREAR TABLAS

CREATE TABLE SOCIOS (
SOCIOS_ID NUMBER PRIMARY KEY,
NOMBRE NVARCHAR2(100),
FECHA_NAC DATE,
SEXO CHAR(1),
TELEFONO NVARCHAR2(20),
CORREO NVARCHAR2(50)
);

CREATE TABLE BARCOS(
BARCOS_ID NUMBER PRIMARY KEY,
MATRICULA NUMBER,
SOCIOS_ID NUMBER,
PATRON_ID NUMBER,
CUOTA NUMBER,
NUM_AMARRE NUMBER
);

CREATE TABLE SALIDAS(
SALIDAD_ID NUMBER PRIMARY KEY,
FECHA_HORA DATE,
DESTINOS VARCHAR2(100),
MATRICULA NUMBER,
SOCIOS_ID NUMBER,
TRIPULANTES_ID NUMBER
);

CREATE TABLE TRIPULANTES(
TRIPULANTES_ID NUMBER PRIMARY KEY,
NOMBRE VARCHAR2(100),
TELEFONO VARCHAR2(10),
DESTINO VARCHAR2(100),
SOCIOS_ID NUMBER,
BARCOS_ID NUMBER
);

CREATE TABLE PATRON (
PATRON_ID NUMBER PRIMARY KEY,
NOMBRE VARCHAR2(100),
CORREO VARCHAR2(50),
BARCOS_ID NUMBER,
NUM_AMARRE NUMBER,
SOCIOS_ID NUMBER
);


--CREAR LLAVES FORANEAS

--BARCOS
ALTER TABLE BARCOS ADD CONSTRAINT FK_BARCOS_ID
FOREIGN KEY (SOCIOS_ID)
REFERENCES SOCIOS(SOCIOS_ID);

ALTER TABLE BARCOS ADD CONSTRAINT FK_BARCOS_PATRON
FOREIGN KEY (PATRON_ID)
REFERENCES PATRON(PATRON_ID);

--SALIDAS
ALTER TABLE SALIDAS ADD CONSTRAINT FK_SOCIOS_ID
FOREIGN KEY(SOCIOS_ID)
REFERENCES SOCIOS (SOCIOS_ID);































